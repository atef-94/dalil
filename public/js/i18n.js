export function t(locale, key) {
  return STRINGS[locale]?.[key] ?? STRINGS.en[key] ?? key;
}

// Western (Latin) digits in both locales — standard practice for Arabic
// business/finance software, where figures must stay visually consistent
// with amounts elsewhere in the UI; only wording and grouping change.
const NUMBER_LOCALE = { en: 'en-US-u-nu-latn', ar: 'ar-EG-u-nu-latn' };

/** Locale-aware number formatting for stat cards, tables, and totals. */
export function formatNumber(locale, value, options) {
  if (value === null || value === undefined || value === '') return '—';
  const n = Number(value);
  if (Number.isNaN(n)) return String(value);
  return new Intl.NumberFormat(NUMBER_LOCALE[locale] || NUMBER_LOCALE.en, options).format(n);
}

export function formatDate(locale, value, options = { dateStyle: 'medium' }) {
  if (!value) return '—';
  const d = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(d.getTime())) return '—';
  return new Intl.DateTimeFormat(NUMBER_LOCALE[locale] || NUMBER_LOCALE.en, options).format(d);
}

export function formatDateTime(locale, value) {
  return formatDate(locale, value, { dateStyle: 'medium', timeStyle: 'short' });
}
