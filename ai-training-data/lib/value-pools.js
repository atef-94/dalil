// Deterministic PRNG (mulberry32) so the generated dataset is reproducible
// across runs without relying on Math.random, which would make dedup/debug
// diffs noisy between generation passes.
export function makeRng(seed) {
  let a = seed >>> 0;
  return {
    next() {
      a |= 0; a = (a + 0x6D2B79F5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0);
    },
  };
}

export function pickFrom(pool, rng) {
  return pool[rng.next() % pool.length];
}
